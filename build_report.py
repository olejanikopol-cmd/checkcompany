def build():
    for i, r in enumerate(ROWS, 1):
        r["n"] = i
        r["size"] = SIZE_LABEL[r["size"]]
    assert len(ROWS) == 100, len(ROWS)

    with open("UK_100_companies.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow([title for _, title in COLUMNS])
        for r in ROWS:
            w.writerow([r[key] for key, _ in COLUMNS])

    wb = Workbook()
    ws = wb.active
    ws.title = "100 компаний"
    header_fill = PatternFill("solid", fgColor="1F3864")
    prio_fill = {"A": "C6EFCE", "B": "FFEB9C", "C": "F4CCCC"}
    ws.append([title for _, title in COLUMNS])
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = header_fill
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    for r in ROWS:
        ws.append([r[key] for key, _ in COLUMNS])
    widths = {"n": 5, "company": 28, "ticker": 9, "market": 10, "size": 16, "sector": 20, "site": 24,
              "problem": 70, "offer": 50, "niche": 9, "priority": 10, "dm": 34, "emails": 44,
              "pattern": 40, "phone": 26, "notes": 34, "sources": 50}
    for idx, (key, _) in enumerate(COLUMNS, 1):
        ws.column_dimensions[get_column_letter(idx)].width = widths[key]
    prio_col = [k for k, _ in COLUMNS].index("priority") + 1
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
        p = row[prio_col - 1]
        p.fill = PatternFill("solid", fgColor=prio_fill[p.value])
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = ws.dimensions

    ns = wb.create_sheet("Ниши")
    ns.append(["Код", "Ниша", "Компаний в списке", "Компании (приоритет A)"])
    for c in ns[1]:
        c.font = Font(bold=True)
    for code, title in NICHES.items():
        matched = [r for r in ROWS if code in r["niche"]]
        top = [r["company"] for r in matched if r["priority"] == "A"]
        ns.append([code, title, len(matched), ", ".join(top)])
    for col, w in zip("ABCD", (6, 80, 18, 90)):
        ns.column_dimensions[col].width = w
    for row in ns.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")

    ts = wb.create_sheet("Топ для старта (A)")
    ts.append(["Компания", "Что не так", "Что предложить", "Кому писать", "Email"])
    for c in ts[1]:
        c.font = Font(bold=True)
    for r in ROWS:
        if r["priority"] == "A":
            ts.append([r["company"], r["problem"], r["offer"], r["dm"], r["emails"]])
    for col, w in zip("ABCDE", (30, 70, 50, 34, 44)):
        ts.column_dimensions[col].width = w
    for row in ts.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")

    wb.save("UK_100_companies.xlsx")
    counts = {p: sum(r["priority"] == p for r in ROWS) for p in "ABC"}
    print("rows:", len(ROWS), "priority:", counts)


if __name__ == "__main__":
    build()
